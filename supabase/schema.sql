create table if not exists products (
  id            uuid primary key default gen_random_uuid(),
  code          text not null unique,              -- EW-01 (প্রিফিক্স site.ts-এ)
  name          text not null,
  slug          text not null unique,
  category      text not null,                     -- key আসে src/config/site.ts → categories থেকে
  price         integer not null,                  -- বিক্রয় মূল্য, টাকায়
  compare_price integer,                           -- কাটা দাম
  images        text[] not null default '{}',
  description   text,
  video_url     text,                              -- ইউটিউব লিংক (ঐচ্ছিক)
  fb_id         text,                              -- পিক্সেলের content_id — পুরনো WooCommerce আইডি (1483)
  active        boolean not null default true,
  sort          integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists products_active_idx on products (active, sort);
create index if not exists products_category_idx on products (category) where active;

-- ভ্যারিয়েন্ট ও স্টক
-- opt_key/opt_label = সাইজ, বয়স, রং — যা-ই হোক। সাইজবিহীন পণ্যে
-- একটিমাত্র সারি থাকে, তখন সাইটে বাছার ঘরটাই দেখায় না।
create table if not exists product_variants (
  id          uuid primary key default gen_random_uuid(),
  product_id  uuid not null references products(id) on delete cascade,
  opt_key     text not null,                       -- 32, 34, 36 … বা 'one'
  opt_label   text not null,                       -- ৩২, ৩৪ … বা 'এক সাইজ'
  -- রঙের ঘর। খালি স্ট্রিং = এই পণ্যের রঙ নেই (তখন পেইজে রঙ বাছার ঘরও নেই)
  color_key   text not null default '',            -- red, black … বা ''
  color_label text,                                -- লাল, কালো …
  color_hex   text,                                -- #D32F2F — গোল বোতামের রং
  stock       integer not null default 0,          -- এই সাইজ+রঙ জোড়ার স্টক
  sort        integer not null default 0,
  -- একই সাইজ একাধিক রঙে থাকতে পারে, তাই রঙসহ ইউনিক
  unique (product_id, opt_key, color_key)
);
create index if not exists variants_product_idx on product_variants (product_id);

