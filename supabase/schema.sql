-- ---------------------------------------------------------------------
-- রিপোর্টিং ভিউ — অ্যাডমিন ড্যাশবোর্ডের জন্য
-- ---------------------------------------------------------------------
create or replace view daily_stats
with (security_invoker = on) as
select
  date_trunc('day', created_at)::date               as day,
  count(*)                                          as orders,
  count(*) filter (where status <> 'cancelled')      as valid_orders,
  count(*) filter (where status = 'delivered')       as delivered,
  count(*) filter (where status = 'returned')        as returned,
  coalesce(sum(total) filter (where status = 'delivered'), 0) as revenue
from orders
group by 1;

create or replace view campaign_stats
with (security_invoker = on) as
select
  coalesce(utm_campaign, '(direct)')                as campaign,
  coalesce(utm_content,  '(none)')                  as adset,
  count(*)                                          as orders,
  count(*) filter (where status = 'delivered')      as delivered,
  count(*) filter (where status = 'returned')       as returned,
  coalesce(sum(total) filter (where status = 'delivered'), 0) as revenue
from orders
group by 1, 2;

